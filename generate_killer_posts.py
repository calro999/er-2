    out = []
    for i in items:
        c = i.get("content_id")
        if not c or c in cache: continue
        t = i.get("title","")
        gs = " ".join(g.get("name","") for g in i.get("iteminfo",{}).get("genre",[]))
        if any(w in t+" "+gs for w in ex): continue
        imgs = i.get("imageURL",{})
        if not imgs or not (imgs.get("large") or imgs.get("list")): continue
