# レビュー生成エンジン v4 ― 見出し×本文独立選択方式
# ====================================================================
def build_review(item, gen_idx):
    title = item.get("title","")
    genres = [g.get("name","") for g in item.get("iteminfo",{}).get("genre",[])]
    actresses = [a.get("name","") for a in item.get("iteminfo",{}).get("actress",[])]
    maker = item.get("iteminfo",{}).get("maker",[{}])[0].get("name","")
    cid = item.get("content_id","")
    
    G = "、".join(genres[:5]) if genres else "ドラマ"
    TG = genres[0] if genres else "ドラマ"
    A = actresses[0] if actresses else ""
    M = maker or "制作スタジオ"
    T = title
    
    # cid + gen_idx でユニークシード
    s = int(hashlib.md5(f"{cid}_{gen_idx}".encode()).hexdigest()[:12], 16)
    
    def fmt(tmpl):
        return tmpl.replace("{T}",T).replace("{M}",M).replace("{G}",G).replace("{TG}",TG).replace("{A}",A)
    
    # 各セクションの見出しと本文を独立に選択
    h2_h = H2_HEADS[s % len(H2_HEADS)]
    h2_b = H2_BODIES[(s >> 7) % len(H2_BODIES)]
    h2 = f"<h2>{fmt(h2_h)}</h2>\n<p>{fmt(h2_b)}</p>"
    
    parts = [h2]
    
    if A:
        a_h = ACT_HEADS[(s >> 11) % len(ACT_HEADS)]
        a_b = ACT_BODIES[(s >> 15) % len(ACT_BODIES)]
        parts.append(f"<h3>{fmt(a_h)}</h3>\n<p>{fmt(a_b)}</p>")
    
    g_h = GNR_HEADS[(s >> 19) % len(GNR_HEADS)]
    g_b = GNR_BODIES[(s >> 23) % len(GNR_BODIES)]
    parts.append(f"<h3>{fmt(g_h)}</h3>\n<p>{fmt(g_b)}</p>")
    
    p_h = PRD_HEADS[(s >> 27) % len(PRD_HEADS)]
    p_b = PRD_BODIES[(s >> 31) % len(PRD_BODIES)]
    parts.append(f"<h3>{fmt(p_h)}</h3>\n<p>{fmt(p_b)}</p>")
    
    e_h = END_HEADS[(s >> 35) % len(END_HEADS)]
    e_b = END_BODIES[(s >> 39) % len(END_BODIES)]
    parts.append(f"<h3>{fmt(e_h)}</h3>\n<p>{fmt(e_b)}</p>")
    
    return "\n\n".join(parts)


def save_post(pd):
    os.makedirs(POSTS_DIR, exist_ok=True)
    fp = os.path.join(POSTS_DIR, f"{pd['id']}.json")
    with open(fp,"w",encoding="utf-8") as f:
        json.dump(pd, f, ensure_ascii=False, indent=2)
    print(f"    ✅ {fp}")

